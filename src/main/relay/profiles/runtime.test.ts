import { describe, expect, it } from 'vitest'
import { profileRuntimeSource } from '../__fixtures__/profile-runtime'
import { compileProfileRuntime } from './runtime'

describe('Redacted declaration catalogue and bounded isolated runtime generation', () => {
  it('preserves process-name routing and rejects missing targets or extra rule parameters', () => {
    const rules = ['PROCESS-NAME,Clash Verge,DIRECT', 'PROCESS-NAME,node,REJECT', 'MATCH,DIRECT']
    expect(
      JSON.parse(compileProfileRuntime(JSON.stringify({ rules })).configuration ?? '{}').rules
    ).toEqual(rules)
    for (const rule of [
      'PROCESS-NAME,,DIRECT',
      'PROCESS-NAME,node,Missing',
      'PROCESS-NAME,node,DIRECT,no-resolve'
    ])
      expect(compileProfileRuntime(JSON.stringify({ rules: [rule] })).configuration).toBeUndefined()
  })
  it('keeps node/group/rule data but forces isolation and never returns credentials in the catalogue', () => {
    const built = compileProfileRuntime(profileRuntimeSource)
    expect(built.issues).toEqual([])
    expect(built.catalogue).toMatchObject({
      nodes: [{ name: 'Node', type: 'ss' }],
      groups: [{ name: 'Group', type: 'select', members: ['Node', 'DIRECT'] }]
    })
    expect(JSON.stringify(built.catalogue)).not.toContain('PRIVATE')
    const config = JSON.parse(built.configuration ?? '{}')
    expect(config).toMatchObject({
      port: 0,
      'socks-port': 0,
      'mixed-port': 0,
      'redir-port': 0,
      'tproxy-port': 0,
      'external-controller': '',
      'allow-lan': false,
      dns: { enable: false },
      tun: { enable: false },
      ntp: { enable: false },
      'geo-auto-update': false,
      'proxy-providers': {},
      'rule-providers': {}
    })
    expect(config.proxies[0].password).toBe('PRIVATE-password') // Retained only in the private generated bytes.
    expect(config.rules).toHaveLength(3)
    expect(config['unknown-setting']).toBeUndefined()
    expect(config.dns['nameserver-policy']).toBeUndefined()
    expect(compileProfileRuntime(profileRuntimeSource).configuration).toBe(built.configuration)
  })
  it.each([
    'proxies: [{name: N, type: unknown-protocol}]',
    'proxies: [{name: N, type: ss, plugin: external}]',
    'proxies: [{name: N, type: vless, certificate: /PRIVATE/file}]',
    'proxies: [{name: N, type: vless, ws-opts: {headers: {Host: {bad: value}}}}]',
    'proxy-groups: [{name: G, type: url-test, proxies: [DIRECT]}]',
    'proxy-groups: [{name: G, type: relay, proxies: [DIRECT]}]',
    'proxy-providers: {External: {type: http, url: "https://PRIVATE.invalid/sub"}}',
    'rule-providers: {External: {type: file, path: /PRIVATE/rules}}',
    'rules: ["GEOIP,CN,DIRECT"]',
    'rules: ["RULE-SET,External,DIRECT"]',
    'rules: ["MATCH,Missing"]',
    'rules: ["DOMAIN,example.invalid,DIRECT,extra"]'
  ])('blocks unsupported/dependent material instead of silently dropping it: %s', (text) => {
    const result = compileProfileRuntime(text)
    expect(result.configuration).toBeUndefined()
    expect(result.issues.length).toBeGreaterThan(0)
    expect(JSON.stringify(result.issues)).not.toContain('PRIVATE')
  })
  it('includes declarations and flags dynamic/provider membership even when checking is blocked', () => {
    const built =
      compileProfileRuntime(`proxy-providers: {Remote: {type: http, url: 'https://PRIVATE.invalid'}}
proxy-groups: [{name: Auto, type: select, use: [Remote], include-all: true}]`)
    expect(built.catalogue).toMatchObject({
      proxyProviders: ['Remote'],
      groups: [{ name: 'Auto', providers: ['Remote'], dynamic: true }]
    })
    expect(built.configuration).toBeUndefined()
    expect(JSON.stringify(built.catalogue)).not.toContain('PRIVATE')
  })
  it('bounds declaration payloads and explicitly labels truncation', () => {
    const result = compileProfileRuntime(
      JSON.stringify({
        proxies: Array.from({ length: 150 }, (_, i) => ({
          name: `${i}-${'字'.repeat(240)}`,
          type: 'socks5',
          server: '127.0.0.1',
          port: 1,
          password: 'PRIVATE'
        }))
      })
    )
    expect(result.catalogue.truncated).toBe(true)
    expect(result.catalogue.nodes.length).toBeLessThanOrEqual(100)
    expect(Buffer.byteLength(JSON.stringify(result.catalogue))).toBeLessThan(65536)
  })
  it('preserves inline rule sets and exact routing order while retaining disabled listeners and geodata updates', () => {
    const source = {
      'rule-providers': {
        Domains: { type: 'inline', behavior: 'domain', payload: ['+.example.test'] },
        Networks: { type: 'inline', behavior: 'ipcidr', payload: ['127.0.0.0/8'] }
      },
      rules: ['RULE-SET,Domains,REJECT', 'RULE-SET,Networks,DIRECT,no-resolve', 'MATCH,REJECT']
    }
    const built = compileProfileRuntime(JSON.stringify(source))
    expect(built.issues).toEqual([])
    const configuration = JSON.parse(built.configuration ?? '{}')
    expect(configuration['rule-providers']).toEqual(source['rule-providers'])
    expect(configuration.rules).toEqual(source.rules)
    expect(configuration).toMatchObject({
      port: 0,
      dns: { enable: false },
      tun: { enable: false },
      'geo-auto-update': false
    })
    expect(built.catalogue.ruleProviders).toEqual(['Domains', 'Networks'])
  })
  it('projects a pure classical rule set and blocks any dependent entry in the same set', () => {
    const input = {
      'rule-providers': {
        Classical: {
          type: 'inline',
          behavior: 'classical',
          payload: ['DOMAIN,example.test', 'IP-CIDR,127.0.0.0/8,no-resolve']
        }
      },
      rules: ['RULE-SET,Classical,DIRECT', 'MATCH,REJECT']
    }
    const built = compileProfileRuntime(JSON.stringify(input))
    expect(built.issues).toEqual([])
    expect(JSON.parse(built.configuration ?? '{}')['rule-providers']).toEqual(
      input['rule-providers']
    )
    input['rule-providers'].Classical.payload.push('GEOIP,CN')
    expect(compileProfileRuntime(JSON.stringify(input)).configuration).toBeUndefined()
  })
  it('refuses missing rule-set references, invalid options and unsafe provider names without dropping a set', () => {
    const provider = { type: 'inline', behavior: 'domain', payload: ['example.test'] }
    for (const source of [
      { 'rule-providers': { 'bad/name': provider }, rules: ['MATCH,DIRECT'] },
      { 'rule-providers': { '..': provider }, rules: ['MATCH,DIRECT'] },
      { 'rule-providers': { ' spaced ': provider }, rules: ['MATCH,DIRECT'] },
      { 'rule-providers': { Named: provider }, rules: ['RULE-SET,Missing,DIRECT'] },
      { 'rule-providers': { Named: provider }, rules: ['RULE-SET,Named,Missing'] },
      { 'rule-providers': { Named: provider }, rules: ['RULE-SET,Named,DIRECT,src'] },
      {
        'rule-providers': { Named: { ...provider, url: 'https://private.invalid' } },
        rules: ['MATCH,DIRECT']
      }
    ])
      expect(compileProfileRuntime(JSON.stringify(source)).configuration).toBeUndefined()
  })
})

describe('Smart collector isolated projection', () => {
  it('carries the explicit size while forcing both isolated profile flags false', () => {
    const source =
      profileRuntimeSource +
      '\nprofile: {store-selected: true, store-fake-ip: true, smart-collector-size: 256}\n'
    const built = compileProfileRuntime(source)
    expect(built.issues).toEqual([])
    expect(JSON.parse(built.configuration ?? '{}').profile).toEqual({
      'store-selected': false,
      'store-fake-ip': false,
      'smart-collector-size': 256
    })
  })
  it.each([0, 1.5, '100', 8589934592])(
    'rejects invalid explicit size %j instead of silently dropping it',
    (size) => {
      const source = JSON.parse(compileProfileRuntime(profileRuntimeSource).configuration ?? '{}')
      source.profile = { 'smart-collector-size': size }
      expect(compileProfileRuntime(JSON.stringify(source)).configuration).toBeUndefined()
    }
  )
  it('rejects an unknown sibling profile field in a collector-bearing source', () => {
    expect(
      compileProfileRuntime(
        profileRuntimeSource + '\nprofile: {smart-collector-size: 10, foreign: true}\n'
      ).configuration
    ).toBeUndefined()
  })
})
