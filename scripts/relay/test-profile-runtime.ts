import { lstat, mkdtemp, readFile, realpath, rm, writeFile } from 'fs/promises'
import { join, resolve } from 'path'
import { ProfileStore } from '../../src/main/relay/profiles/store'
import { createProfileRuntimeService } from '../../src/main/relay/profiles/runtime-service'
import { compileProfileRuntime } from '../../src/main/relay/profiles/runtime'
import { profileHash } from '../../src/main/relay/profiles/source'
import { checkProfileRuntime } from '../../src/main/relay/core/profile-check'
import { verifyCoreResource } from '../../src/main/relay/core/resources'
import { profileRuntimeSource } from '../../src/main/relay/__fixtures__/profile-runtime'

const home = await realpath(await mkdtemp('/private/tmp/relay-runtime-contract-'))
const store = new ProfileStore({
  home,
  stateRoot: join(home, 'Library/Application Support/Relay-Preview')
})
const root = resolve('extra/relay/core'),
  rows: { name: string; passed: boolean }[] = []
const check = (name: string, passed: boolean): void => {
  rows.push({ name, passed })
}
let executed = 0
const service = createProfileRuntimeService({
  read: (selection) => store.read(selection),
  check: (source) => {
    ++executed
    return checkProfileRuntime(root, source)
  }
})
const previousInline = process.env.CLASH_CONFIG_STRING
try {
  process.env.CLASH_CONFIG_STRING = '[ deliberately invalid inherited inline YAML'
  const saved = await store.save('Synthetic local', '\uFEFF' + profileRuntimeSource)
  const selection = { id: saved.id, sha256: saved.sha256 }
  const sourceFile = join(store.directory, saved.id, 'profile.yaml')
  const metadataFile = join(store.directory, saved.id, 'metadata.json')
  const beforeSource = await readFile(sourceFile),
    beforeMetadata = await readFile(metadataFile)
  const plan = await service.prepare(selection)
  check(
    'real stored record creates a redacted declaration catalogue',
    plan.catalogue.nodes[0].name === 'Node' &&
      plan.catalogue.groups[0].members.join(',') === 'Node,DIRECT' &&
      !JSON.stringify(plan).includes('PRIVATE')
  )
  check('preparation alone never starts a core', executed === 0)
  check(
    'scope explicitly excludes the full source and activation',
    !plan.active &&
      !plan.fullSourceVerified &&
      plan.scope === 'isolated-projection' &&
      plan.canValidate
  )
  const projection = compileProfileRuntime('\uFEFF' + profileRuntimeSource).configuration
  if (!projection) throw new Error('fixture projection missing')
  const config = JSON.parse(projection)
  check(
    'all five proxy ports are zero in generated config',
    ['port', 'socks-port', 'mixed-port', 'redir-port', 'tproxy-port'].every(
      (key) => config[key] === 0
    )
  )
  check(
    'DNS/TUN/NTP/controllers/providers disabled in generated config',
    !config.dns.enable &&
      !config.tun.enable &&
      !config.ntp.enable &&
      config['external-controller'] === '' &&
      !Object.keys(config['proxy-providers']).length &&
      !Object.keys(config['rule-providers']).length
  )
  const result = await service.check({ evidenceId: plan.evidenceId })
  check(
    'real pinned ARM core accepts the generated isolated projection',
    result.status === 'passed' && result.version === 'v1.19.33'
  )
  check(
    'accepted bytes match prepared runtime hash',
    result.runtimeSHA256 === plan.runtimeSHA256 && result.runtimeSHA256 === profileHash(projection)
  )
  check(
    'inherited dangerous inline config did not replace generated bytes',
    result.status === 'passed'
  )
  check(
    'successful check does not claim full compatibility or enablement',
    !result.active && !result.fullSourceVerified
  )
  check(
    'source and metadata are unchanged by core validation',
    (await readFile(sourceFile)).equals(beforeSource) &&
      (await readFile(metadataFile)).equals(beforeMetadata)
  )
  let repeated = false
  try {
    await service.check({ evidenceId: plan.evidenceId })
  } catch {
    repeated = true
  }
  check('check proof cannot be reused to spawn another process', repeated && executed === 1)
  const stale = await service.prepare(selection)
  await writeFile(sourceFile, beforeSource.toString('utf8') + '# external change\n')
  check(
    'changed saved source blocks actual execution',
    (await service.check({ evidenceId: stale.evidenceId })).status === 'unavailable' &&
      executed === 1
  )
  await writeFile(sourceFile, beforeSource)
  const metaPlan = await service.prepare(selection),
    metadata = JSON.parse(beforeMetadata.toString('utf8'))
  metadata.name = 'Locally changed metadata'
  await writeFile(metadataFile, JSON.stringify(metadata))
  check(
    'changed metadata revision blocks stale execution',
    (await service.check({ evidenceId: metaPlan.evidenceId })).status === 'unavailable' &&
      executed === 1
  )
  await writeFile(metadataFile, beforeMetadata)
  const invalid = profileRuntimeSource.replace('aes-128-gcm', 'invalid-cipher')
  const rejected = await checkProfileRuntime(root, invalid)
  check(
    'real core rejects invalid protocol parameters without disclosing raw logs',
    rejected.status === 'rejected' && !JSON.stringify(rejected).includes('PRIVATE')
  )
  const missing = createProfileRuntimeService({
    read: (value) => store.read(value),
    check: (value) => checkProfileRuntime(join(home, 'missing-core'), value)
  })
  const missingPlan = await missing.prepare(selection)
  check(
    'missing fixed resources return unverified rather than success',
    (await missing.check({ evidenceId: missingPlan.evidenceId })).status === 'unavailable'
  )
  const provider = await store.save(
    'Provider fixture',
    'proxy-providers: {External: {type: http, url: "https://must-not-fetch.invalid"}}'
  )
  const blocked = await service.prepare({ id: provider.id, sha256: provider.sha256 })
  check(
    'provider-backed source is visible but blocked before any core read',
    blocked.catalogue.proxyProviders[0] === 'External' && !blocked.canValidate && executed === 1
  )
  const vless =
    'proxies: [{name: VLESS, type: vless, server: 127.0.0.1, port: 12345, uuid: "00000000-0000-4000-8000-000000000001", tls: false}]\nproxy-groups: [{name: Select, type: select, proxies: [VLESS]}]\nrules: ["MATCH,Select"]'
  check(
    'real core also accepts basic VLESS projection',
    (await checkProfileRuntime(root, vless)).status === 'passed'
  )
  check(
    'saved copies remain private and inactive',
    ((await lstat(sourceFile)).mode & 0o7777) === 0o600 && (await store.list()).activeId === null
  )
} finally {
  if (previousInline === undefined) delete process.env.CLASH_CONFIG_STRING
  else process.env.CLASH_CONFIG_STRING = previousInline
  await service.whenIdle()
  await rm(home, { recursive: true })
}
const pin = await verifyCoreResource(root)
const report = {
  checks: rows.length,
  passed: rows.filter((row) => row.passed).length,
  rows,
  version: pin.version,
  architectureExecuted: process.arch,
  intelRuntimeVerified: process.arch === 'x64',
  actualCoreConfigurationTestExecuted: true,
  commandMode: '-t only',
  fullSourceCompatibilityVerified: false,
  normalTrafficCoreStarted: false,
  actualUserConfigurationImportedOrChanged: false,
  actualSystemProxyDNSOrTUNChanged: false,
  actualClashStoppedReloadedOrRestarted: false,
  appOrBrowserLaunched: false,
  fakeHomeOnly: true,
  syntheticLocalNodesOnly: true,
  actualNodeConnectivityVerified: false,
  networkPacketCapturePerformed: false,
  liveGuardEnabled: false
}
await writeFile('../evidence/profile-runtime-contract.json', JSON.stringify(report, null, 2) + '\n')
process.stdout.write(
  JSON.stringify({ checks: report.checks, passed: report.passed, version: report.version }) + '\n'
)
if (report.checks !== report.passed)
  throw new Error('Profile runtime contract failed; inspect bounded report.')
